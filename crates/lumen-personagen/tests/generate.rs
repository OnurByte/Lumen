use lumen_personagen::{
    Brief, DraftSource, GenerateError, Options, SourceError, draft::guardrail, generate, write_pack,
};
use std::{cell::RefCell, collections::VecDeque};

const BRIEF: &str = r#"
name = "Test Clash"
topic = "Uzaktan çalışma ekipleri güçlendirir mi?"
format = "crossfire"
tone = "esprili, saygılı"

[[agents]]
name = "Ece"
stance = "Uzaktan çalışmanın ekipleri güçlendirdiğini savun."
voice = "female_2"
model = "qwen3:8b"
endpoint = "http://127.0.0.1:11434/v1/chat/completions"
temperature = 0.7
max_tokens = 256

[[agents]]
stance = "Yüz yüze çalışmanın ekip bağını güçlendirdiğini savun."
character = "emekli bir vapur kaptanı gibi konuşan"
voice = "male_1"
model = "qwen3:8b"
endpoint = "http://127.0.0.1:11434/v1/chat/completions"
api_key_env = "LUMEN_TEST_KEY"
temperature = 0.9
max_tokens = 200
"#;

const PERSONA_A: &str = "Sakin, meraklı ve kuru esprili bir tartışmacısın. Kısa cümlelerle konuşur, \
    her itirazı önce kendi sözlerinle özetler sonra yanıtlarsın. Haklı bir noktayı gördüğünde \
    gülümseyerek kabul edersin; abartıdan ve slogan cümlelerinden kaçınırsın.";
const PERSONA_B: &str = "Gür sesli, hikâye anlatmayı seven, eski usul bir anlatıcısın. Argümanlarını \
    denizcilik benzetmeleriyle kurar, ara ara sahneye soru fırlatırsın. İnatçısın ama dürüstsün: \
    iyi bir itirazı duyunca 'rüzgâr döndü' deyip kabul edersin.";

fn answer(first: &str, second: &str) -> String {
    serde_json::json!({
        "first": {"name": first, "persona": PERSONA_A, "position": "Uzaktan çalışmanın ekipleri güçlendirdiğini savun."},
        "second": {"name": second, "persona": PERSONA_B, "position": "Yüz yüze çalışmanın ekip bağını güçlendirdiğini savun."}
    })
    .to_string()
}

struct Scripted {
    answers: RefCell<VecDeque<Result<String, SourceError>>>,
    prompts: RefCell<Vec<String>>,
}

impl Scripted {
    fn new(answers: Vec<Result<String, SourceError>>) -> Self {
        Self {
            answers: RefCell::new(answers.into()),
            prompts: RefCell::default(),
        }
    }
}

impl DraftSource for Scripted {
    fn draft(&self, prompt: &str, schema: &str) -> Result<String, SourceError> {
        assert!(schema.contains("\"additionalProperties\": false"));
        self.prompts.borrow_mut().push(prompt.to_owned());
        self.answers
            .borrow_mut()
            .pop_front()
            .expect("unexpected extra draft call")
    }
    fn describe(&self) -> String {
        "scripted".into()
    }
}

fn options(attempts: u32) -> Options<'static> {
    Options {
        attempts,
        origin: "test.toml",
        progress: &|_, _| {},
    }
}

#[test]
fn accepted_draft_keeps_operator_settings_and_appends_guardrail() {
    let brief = Brief::parse(BRIEF).unwrap();
    let source = Scripted::new(vec![Ok(answer("Ece", "Rıza"))]);
    let generated = generate(&brief, &source, &options(3)).unwrap();
    assert_eq!(generated.attempts, 1);
    let reparsed = ShowPack::parse(&generated.toml).unwrap();
    let [a, b] = &reparsed.agents;
    assert_eq!((a.name.as_str(), b.name.as_str()), ("Ece", "Rıza"));
    assert!(a.persona.ends_with(guardrail(brief.language)));
    assert!(b.persona.starts_with("Gür sesli"));
    assert_eq!((a.voice.as_str(), b.voice.as_str()), ("female_2", "male_1"));
    assert_eq!(b.api_key_env.as_deref(), Some("LUMEN_TEST_KEY"));
    assert_eq!(a.api_key_env, None);
    assert_eq!((a.max_tokens, b.max_tokens), (256, 200));
    assert!((b.temperature - 0.9).abs() < 1e-6);
    assert!(
        generated
            .toml
            .starts_with("# Generated by `lumend generate-pack`")
    );
    let prompt = &source.prompts.borrow()[0];
    assert!(prompt.contains("name: Ece (use exactly)"));
    assert!(prompt.contains("vapur kaptanı"));
    assert!(
        !prompt.contains("qwen3") && !prompt.contains("11434"),
        "runtime settings leaked to writer"
    );
}

#[test]
fn rejected_draft_is_retried_with_reasons() {
    let brief = Brief::parse(BRIEF).unwrap();
    let source = Scripted::new(vec![
        Ok(answer("Mert", "Rıza")),
        Ok("not json".into()),
        Ok(answer("Ece", "Rıza")),
    ]);
    let generated = generate(&brief, &source, &options(3)).unwrap();
    assert_eq!(generated.attempts, 3);
    let prompts = source.prompts.borrow();
    assert!(!prompts[0].contains("REJECTED"));
    assert!(prompts[1].contains("first.name must be exactly \"Ece\""));
    assert!(prompts[2].contains("not valid draft JSON"));
}

#[test]
fn rule_violations_exhaust_attempts() {
    let brief = Brief::parse(BRIEF).unwrap();
    let short = serde_json::json!({
        "first": {"name": "Ece", "persona": "Kısa.", "position": "Bkz https://x.example"},
        "second": {"name": "ece", "persona": "Kısa.", "position": "Bkz https://x.example"}
    })
    .to_string();
    let source = Scripted::new(vec![Ok(short.clone()), Ok(short)]);
    match generate(&brief, &source, &options(2)) {
        Err(GenerateError::Rejected {
            attempts: 2,
            errors,
        }) => {
            let all = errors.join("\n");
            for expected in [
                "first.persona has",
                "\"https://\"",
                "names must differ",
                "personas must differ",
            ] {
                assert!(all.contains(expected), "{expected} missing in {all}");
            }
        }
        other => panic!("unexpected {other:?}"),
    }
}

#[test]
fn fatal_source_errors_stop_immediately_and_transient_ones_retry() {
    let brief = Brief::parse(BRIEF).unwrap();
    let fatal = Scripted::new(vec![Err(SourceError::Fatal("usage limit".into()))]);
    assert!(matches!(
        generate(&brief, &fatal, &options(3)),
        Err(GenerateError::Source(SourceError::Fatal(_)))
    ));
    let flaky = Scripted::new(vec![
        Err(SourceError::Transient("timeout".into())),
        Ok(answer("Ece", "Rıza")),
    ]);
    assert_eq!(generate(&brief, &flaky, &options(3)).unwrap().attempts, 2);
}

#[test]
fn invalid_briefs_fail_before_drafting() {
    for invalid in [
        BRIEF.replace("http://127.0.0.1:11434", "http://example.com"),
        BRIEF.replace("max_tokens = 200", "max_tokens = 0"),
        BRIEF.replace("name = \"Ece\"", "name = \"Ece1\""),
        BRIEF.replace("tone = \"esprili, saygılı\"", "tone = \"\""),
        format!("{BRIEF}\nmodel_override = 'x'"),
        BRIEF.replace("format = \"crossfire\"", "format = \"chaos\""),
    ] {
        assert!(Brief::parse(&invalid).is_err(), "{invalid}");
    }
}

#[test]
fn write_pack_is_atomic_and_refuses_overwrite() {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("pack.toml");
    write_pack(&path, "first", false).unwrap();
    assert!(
        write_pack(&path, "second", false)
            .unwrap_err()
            .contains("--force")
    );
    assert_eq!(std::fs::read_to_string(&path).unwrap(), "first");
    write_pack(&path, "third", true).unwrap();
    assert_eq!(std::fs::read_to_string(&path).unwrap(), "third");
    assert_eq!(
        std::fs::read_dir(dir.path()).unwrap().count(),
        1,
        "temp file left behind"
    );
}

#[test]
fn shipped_briefs_are_valid() {
    let dir = concat!(env!("CARGO_MANIFEST_DIR"), "/../../packs/briefs");
    let mut count = 0;
    for entry in std::fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        if path.extension().is_some_and(|e| e == "toml") {
            Brief::parse(&std::fs::read_to_string(&path).unwrap())
                .unwrap_or_else(|e| panic!("{}: {e}", path.display()));
            count += 1;
        }
    }
    assert!(count >= 1);
}
