//! Offline persona authoring for show packs.
//!
//! Flow: operator brief (TOML) -> writer prompt -> drafting backend (`codex exec` with a strict
//! JSON schema) -> draft validation (retry with the rejection reasons) -> fixed guardrail
//! appended -> merged with operator runtime settings -> [`ShowPack::check`] -> atomic write.
//!
//! The drafting model only ever supplies names, persona and position text. It never chooses
//! models, endpoints, voices, budgets or key variables, and generation never runs during a show.
pub mod avatar;
pub mod brief;
pub mod codex;
pub mod draft;
pub mod prompt;
pub mod review;
pub mod skill;

pub use brief::Brief;
pub use codex::{CodexExec, DraftSource, SourceError};
pub use draft::{DRAFT_SCHEMA, Draft};
use lumen_debate::pack::ShowPack;
use std::{io::Write, path::Path};

#[derive(Debug)]
pub struct Generated {
    pub pack: ShowPack,
    pub toml: String,
    pub attempts: u32,
}

#[derive(Debug)]
pub enum GenerateError {
    Source(SourceError),
    /// All attempts produced drafts that broke the rules; holds the last reasons.
    Rejected {
        attempts: u32,
        errors: Vec<String>,
    },
}

impl std::fmt::Display for GenerateError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Source(e) => write!(f, "drafting failed: {e}"),
            Self::Rejected { attempts, errors } => {
                write!(
                    f,
                    "draft rejected after {attempts} attempt(s): {}",
                    errors.join("; ")
                )
            }
        }
    }
}

pub struct Options<'a> {
    pub attempts: u32,
    /// Shown in the generated file header, e.g. the brief path.
    pub origin: &'a str,
    /// Progress callback (attempt number, outcome).
    pub progress: &'a dyn Fn(u32, &str),
}

/// Shared drafting loop: build prompt (with previous rejection reasons) -> draft -> accept.
/// Transient source failures retry; fatal ones stop immediately.
pub(crate) fn draft_loop<T>(
    source: &dyn DraftSource,
    schema: &str,
    options: &Options,
    mut build: impl FnMut(&[String]) -> String,
    mut accept: impl FnMut(&str) -> Result<T, Vec<String>>,
) -> Result<(T, u32), GenerateError> {
    let attempts = options.attempts.max(1);
    let mut errors: Vec<String> = Vec::new();
    for attempt in 1..=attempts {
        let answer = match source.draft(&build(&errors), schema) {
            Ok(answer) => answer,
            Err(SourceError::Transient(e)) => {
                (options.progress)(attempt, &format!("transient failure: {e}"));
                errors.clear();
                if attempt == attempts {
                    return Err(GenerateError::Source(SourceError::Transient(e)));
                }
                continue;
            }
            Err(fatal) => return Err(GenerateError::Source(fatal)),
        };
        match accept(&answer) {
            Ok(value) => {
                (options.progress)(attempt, "accepted");
                return Ok((value, attempt));
            }
            Err(e) => {
                (options.progress)(attempt, &format!("rejected: {}", e.join("; ")));
                errors = e;
            }
        }
    }
    Err(GenerateError::Rejected { attempts, errors })
}

pub fn generate(
    brief: &Brief,
    source: &dyn DraftSource,
    options: &Options,
) -> Result<Generated, GenerateError> {
    let backend = source.describe();
    let ((pack, toml), attempts) = draft_loop(
        source,
        DRAFT_SCHEMA,
        options,
        |errors| prompt::build(brief, errors),
        |answer| {
            let draft = Draft::parse(answer)?;
            let errors = draft.validate(brief);
            if !errors.is_empty() {
                return Err(errors);
            }
            let pack = brief.assemble(draft.into_creative(brief.language));
            pack.check()
                .map_err(|e| vec![format!("assembled pack invalid: {e}")])?;
            let toml = render(&pack, options.origin, &backend).map_err(|e| vec![e])?;
            Ok((pack, toml))
        },
    )?;
    Ok(Generated {
        pack,
        toml,
        attempts,
    })
}

fn render(pack: &ShowPack, origin: &str, backend: &str) -> Result<String, String> {
    let body = toml::to_string_pretty(pack).map_err(|e| format!("serialize: {e}"))?;
    let header = format!(
        "# Generated by `lumend generate-pack` from {origin} via {backend}.\n\
         # Names/personas/positions are model-drafted; runtime settings come from the brief.\n\
         # Review before broadcast. Regenerate from the brief instead of hand-merging.\n\n"
    );
    let text = header + &body;
    // Round-trip proves the written file is exactly what validate-pack/serve will accept.
    ShowPack::parse(&text).map_err(|e| format!("round-trip: {e}"))?;
    Ok(text)
}

/// Writes atomically (temp file + rename in the target directory). Refuses to replace an
/// existing pack unless `force`.
pub fn write_pack(path: &Path, text: &str, force: bool) -> Result<(), String> {
    if !force && path.exists() {
        return Err(format!(
            "{} exists; pass --force to replace it",
            path.display()
        ));
    }
    let dir = path
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let mut file = tempfile::NamedTempFile::new_in(dir).map_err(|e| e.to_string())?;
    file.write_all(text.as_bytes()).map_err(|e| e.to_string())?;
    file.as_file().sync_all().map_err(|e| e.to_string())?;
    if force {
        file.persist(path).map_err(|e| e.error.to_string())?;
    } else {
        file.persist_noclobber(path)
            .map_err(|e| e.error.to_string())?;
    }
    Ok(())
}
